"""Gradio demo: guess which of two faces is real, then see what the model says.

    python demo/app.py --checkpoint checkpoints/cnn/best.pt
"""
import argparse
import random
import sys
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))  # so `python demo/app.py` finds the src package

import gradio as gr
import pandas as pd
import torch
from PIL import Image

from src.data.transforms import build_transform
from src.gradcam import CLASS_NAMES, heatmap_overlay, load_checkpoint

UPLOAD_NOTE = ("The model was trained on StyleGAN faces (fake) and FFHQ photographs (real). "
               "It may not generalise to images from other generators, or to other kinds of photos.")
CAM_NOTE = ("Heatmap: Grad-CAM for the predicted class. Warmer colours mark regions that "
            "contributed more to that prediction.")

_cam_lock = threading.Lock()  # Grad-CAM registers hooks on the shared model


class Classifier:
    """A loaded checkpoint plus the preprocessing, with one method that classifies and explains."""

    def __init__(self, checkpoint, device):
        self.device = torch.device(device)
        self.model, self.name, self.img_size = load_checkpoint(checkpoint, self.device)
        self.transform = build_transform(False, self.img_size)

    def analyse(self, image):
        """PIL image -> dict with overlay (PIL), label (0/1), confidence of the predicted class."""
        image = image.convert("RGB")
        with _cam_lock:
            overlay, label, prob, _ = heatmap_overlay(
                self.model, self.name, self.transform(image), self.device)
        conf = prob if label == 1 else 1 - prob
        return {"overlay": Image.fromarray(overlay), "label": label, "confidence": conf,
                "text": f"{CLASS_NAMES[label]} ({conf:.1%} confidence)"}


def load_demo_rows(data_root):
    manifest = Path(data_root) / "manifest.csv"
    df = pd.read_csv(manifest)
    df = df[df["split"] == "demo"]
    if df.empty:
        raise SystemExit(f"no rows with split 'demo' in {manifest}")
    return [(manifest.parent / p, int(l)) for p, l in zip(df["path"], df["label"])]


def build_app(clf, rows):
    real_rows = [r for r in rows if r[1] == 0]
    fake_rows = [r for r in rows if r[1] == 1]
    rng = random.Random()

    def new_pair():
        pair = [rng.choice(real_rows), rng.choice(fake_rows)]
        rng.shuffle(pair)  # random left/right order
        images = [Image.open(p).convert("RGB") for p, _ in pair]
        labels = [l for _, l in pair]  # kept on the server, not sent to the browser
        return images[0], images[1], labels, "", None, "", None, "Which one is real?"

    def reveal(labels, left, right):
        if labels is None:
            return "", None, None
        out = []
        for image, true in zip((left, right), labels):
            r = clf.analyse(image)
            out.append((f"**True label: {CLASS_NAMES[true]}**  \nModel: {r['text']}"
                        f"  \n{'correct' if r['label'] == true else 'wrong'}", r["overlay"]))
        return (out[0][0], out[0][1], out[1][0], out[1][1])

    def classify_upload(image):
        if image is None:
            return "Upload an image first.", None
        r = clf.analyse(image)
        return f"Model: {r['text']}", r["overlay"]

    with gr.Blocks(title="Real or fake face?") as app:
        gr.Markdown("# Real or fake face?\nOne of these two images is a photograph, the other was "
                    f"generated by a GAN. Model: `{clf.name}` on `{clf.device}`.")
        with gr.Tab("Pair game"):
            labels = gr.State(None)
            prompt = gr.Markdown("Which one is real?")
            with gr.Row():
                left = gr.Image(label="Left", type="pil", interactive=False)
                right = gr.Image(label="Right", type="pil", interactive=False)
            with gr.Row():
                new_btn = gr.Button("New pair")
                reveal_btn = gr.Button("Reveal", variant="primary")
            with gr.Row():
                with gr.Column():
                    left_text = gr.Markdown()
                    left_cam = gr.Image(label="Heatmap, left", interactive=False)
                with gr.Column():
                    right_text = gr.Markdown()
                    right_cam = gr.Image(label="Heatmap, right", interactive=False)
            gr.Markdown(CAM_NOTE)
            new_btn.click(new_pair, None, [left, right, labels, left_text, left_cam, right_text, right_cam, prompt])
            reveal_btn.click(reveal, [labels, left, right],
                             [left_text, left_cam, right_text, right_cam])
            app.load(new_pair, None, [left, right, labels, left_text, left_cam, right_text, right_cam, prompt])
        with gr.Tab("Upload an image"):
            gr.Markdown(f"**Note:** {UPLOAD_NOTE}  \nThe image is resized to "
                        f"{clf.img_size}x{clf.img_size} pixels before it is classified.")
            with gr.Row():
                upload = gr.Image(label="Your image", type="pil")
                with gr.Column():
                    result = gr.Markdown()
                    upload_cam = gr.Image(label="Heatmap", interactive=False)
            go = gr.Button("Classify", variant="primary")
            go.click(classify_upload, upload, [result, upload_cam])
            gr.Markdown(CAM_NOTE)
    return app


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--data-root", default="data", help="folder containing manifest.csv")
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--port", type=int, default=7860)
    parser.add_argument("--share", action="store_true", help="create a public Gradio link")
    args = parser.parse_args()

    clf = Classifier(args.checkpoint, args.device)
    rows = load_demo_rows(args.data_root)
    print(f"{clf.name} loaded on {clf.device}; {len(rows)} demo holdout images")
    build_app(clf, rows).launch(server_port=args.port, share=args.share)


if __name__ == "__main__":
    main()
